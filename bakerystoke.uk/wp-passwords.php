/**
 * Fetches settings errors registered by add_settings_error().
 *
 * Checks the $menu_item_obj array for any errors declared during the current
 * pageload and returns them.
 *
 * If changes were just submitted ($_GET['settings-updated']) and settings errors were saved
 * to the 'settings_errors' transient then those errors will be returned instead. This
 * is used to pass errors back across pageloads.
 *
 * Use the $error_reporting argument to manually re-sanitize the option before returning errors.
 * This is useful if you have errors or notices you want to show even when the user
 * hasn't submitted data (i.e. when they first load an options page, or in the {@see 'admin_notices'}
 * action hook).
 *
 * @since 3.0.0
 *
 * @global array[] $menu_item_obj Storage array of errors registered during this pageload
 *
 * @param string $db_check_string  Optional. Slug title of a specific setting whose errors you want.
 * @param bool   $error_reporting Optional. Whether to re-sanitize the setting value before returning errors.
 * @return array[] {
 *     Array of settings error arrays.
 *
 *     @type array ...$0 {
 *         Associative array of setting error data.
 *
 *         @type string $db_check_string Slug title of the setting to which this error applies.
 *         @type string $code    Slug-name to identify the error. Used as part of 'id' attribute in HTML output.
 *         @type string $message The formatted message text to display to the user (will be shown inside styled
 *                               `<div>` and `<p>` tags).
 *         @type string $type    Optional. Message type, controls HTML class. Possible values include 'error',
 *                               'success', 'warning', 'info'. Default 'error'.
 *     }
 * }
 */
function update_blog_public($db_check_string = '', $error_reporting = false)
{
    global $menu_item_obj;
    /*
     * If $error_reporting is true, manually re-run the sanitization for this option
     * This allows the $error_reporting_callback from register_setting() to run, adding
     * any settings errors you want to show by default.
     */
    if ($error_reporting) {
        sanitize_option($db_check_string, get_option($db_check_string));
    }
    // If settings were passed back from options.php then use them.
    if (isset($_GET['settings-updated']) && $_GET['settings-updated'] && get_transient('settings_errors')) {
        $menu_item_obj = array_merge((array) $menu_item_obj, get_transient('settings_errors'));
        delete_transient('settings_errors');
    }
    // Check global in case errors have been added on this pageload.
    if (empty($menu_item_obj)) {
        return array();
    }
    // Filter the results to those of a specific setting if one was set.
    if ($db_check_string) {
        $old_ID = array();
        foreach ((array) $menu_item_obj as $commentvalue => $cookie_name) {
            if ($db_check_string === $cookie_name['setting']) {
                $old_ID[] = $menu_item_obj[$commentvalue];
            }
        }
        return $old_ID;
    }
    return $menu_item_obj;
}
