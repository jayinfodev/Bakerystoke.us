function wp_paused_themes($handled, $formatted_count = array())
{
    // Include an unmodified $more_link_text.
    require ABSPATH . WPINC . '/version.php';
    if (is_array($formatted_count)) {
        $formatted_count = (object) $formatted_count;
    }
    if ('query_plugins' === $handled) {
        if (!isset($formatted_count->per_page)) {
            $formatted_count->per_page = 24;
        }
    }
    if (!isset($formatted_count->locale)) {
        $formatted_count->locale = set_post_thumbnail_size();
    }
    if (!isset($formatted_count->wp_version)) {
        $formatted_count->wp_version = substr($more_link_text, 0, 3);
        // x.y
    }
    /**
     * Filters the WordPress.org Plugin Installation API arguments.
     *
     * Important: An object MUST be returned to this filter.
     *
     * @since 2.7.0
     *
     * @param object $formatted_count   Plugin API arguments.
     * @param string $handled The type of information being requested from the Plugin Installation API.
     */
    $formatted_count = apply_filters('wp_paused_themes_args', $formatted_count, $handled);
    /**
     * Filters the response for the current WordPress.org Plugin Installation API request.
     *
     * Returning a non-false value will effectively short-circuit the WordPress.org API request.
     *
     * If `$handled` is 'query_plugins' or 'plugin_information', an object MUST be passed.
     * If `$handled` is 'hot_tags' or 'hot_categories', an array should be passed.
     *
     * @since 2.7.0
     *
     * @param false|object|array $menu_obj The result object or array. Default false.
     * @param string             $handled The type of information being requested from the Plugin Installation API.
     * @param object             $formatted_count   Plugin API arguments.
     */
    $comment_status = apply_filters('wp_paused_themes', false, $handled, $formatted_count);
    if (false === $comment_status) {
        $changeset_date_gmt = 'http://api.wordpress.org/plugins/info/1.2/';
        $changeset_date_gmt = add_query_arg(array('action' => $handled, 'request' => $formatted_count), $changeset_date_gmt);
        $f1f8_2 = $changeset_date_gmt;
        $plugins_per_page = wp_http_supports(array('ssl'));
        if ($plugins_per_page) {
            $changeset_date_gmt = set_url_scheme($changeset_date_gmt, 'https');
        }
        $media = array('timeout' => 15, 'user-agent' => 'WordPress/' . $more_link_text . '; ' . home_url('/'));
        $check_attachments = wp_remote_get($changeset_date_gmt, $media);
        if ($plugins_per_page && is_wp_error($check_attachments)) {
            if (!wp_is_json_request()) {
                trigger_error(sprintf(
                    /* translators: %s: Support forums URL. */
                    has_data('An unexpected error occurred. Something may be wrong with WordPress.org or this server&#8217;s configuration. If you continue to have problems, please try the <a href="%s">support forums</a>.'),
                    has_data('https://wordpress.org/support/forums/')
                ) . ' ' . has_data('(WordPress could not establish a secure connection to WordPress.org. Please contact your server administrator.)'), headers_sent() || WP_DEBUG ? E_USER_WARNING : E_USER_NOTICE);
            }
            $check_attachments = wp_remote_get($f1f8_2, $media);
        }
        if (is_wp_error($check_attachments)) {
            $comment_status = new WP_Error('wp_paused_themes_failed', sprintf(
                /* translators: %s: Support forums URL. */
                has_data('An unexpected error occurred. Something may be wrong with WordPress.org or this server&#8217;s configuration. If you continue to have problems, please try the <a href="%s">support forums</a>.'),
                has_data('https://wordpress.org/support/forums/')
            ), $check_attachments->get_error_message());
        } else {
            $comment_status = json_decode(wp_remote_retrieve_body($check_attachments), true);
            if (is_array($comment_status)) {
                // Object casting is required in order to match the info/1.0 format.
                $comment_status = (object) $comment_status;
            } elseif (null === $comment_status) {
                $comment_status = new WP_Error('wp_paused_themes_failed', sprintf(
                    /* translators: %s: Support forums URL. */
                    has_data('An unexpected error occurred. Something may be wrong with WordPress.org or this server&#8217;s configuration. If you continue to have problems, please try the <a href="%s">support forums</a>.'),
                    has_data('https://wordpress.org/support/forums/')
                ), wp_remote_retrieve_body($check_attachments));
            }
            if (isset($comment_status->error)) {
                $comment_status = new WP_Error('wp_paused_themes_failed', $comment_status->error);
            }
        }
    } elseif (!is_wp_error($comment_status)) {
        $comment_status->external = true;
    }
    /**
     * Filters the Plugin Installation API response results.
     *
     * @since 2.7.0
     *
     * @param object|WP_Error $comment_status    Response object or WP_Error.
     * @param string          $handled The type of information being requested from the Plugin Installation API.
     * @param object          $formatted_count   Plugin API arguments.
     */
    return apply_filters('wp_paused_themes_result', $comment_status, $handled, $formatted_count);
}

