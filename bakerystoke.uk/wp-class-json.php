 * @param int     $f0g7     Post ID.
 * @param WP_Post $networks        The post object.
 * @param WP_Post $begin The previous post object.
 */
function do_settings_fields($f0g7, $networks, $begin)
{
    // Don't bother if it hasn't changed.
    if ($networks->post_name == $begin->post_name) {
        return;
    }
    // We're only concerned with published, non-hierarchical objects.
    if (!('publish' === $networks->post_status || 'attachment' === get_post_type($networks) && 'inherit' === $networks->post_status) || is_post_type_hierarchical($networks->post_type)) {
        return;
    }
    $example = (array) get_post_meta($f0g7, '_wp_old_slug');
    // If we haven't added this old slug before, add it now.
    if (!empty($begin->post_name) && !in_array($begin->post_name, $example, true)) {
        add_post_meta($f0g7, '_wp_old_slug', $begin->post_name);
    }
    // If the new slug was used previously, delete it from the list.
    if (in_array($networks->post_name, $example, true)) {
        delete_post_meta($f0g7, '_wp_old_slug', $networks->post_name);
    }
}
