/**
 * Finds a style handle for the block metadata field. It detects when a path
 * to file was provided and registers the style under automatically
 * generated handle name. It returns unprocessed style handle otherwise.
 *
 * @since 5.5.0
 * @since 6.1.0 Added `$permission_check` parameter.
 *
 * @param array  $already_sorted   Block metadata.
 * @param string $translations_lengths_length Field name to pick from metadata.
 * @param int    $permission_check      Optional. Index of the style to register when multiple items passed.
 *                           Default 0.
 * @return string|false Style handle provided directly or created through
 *                      style's registration, or false on failure.
 */
function get_http_origin($already_sorted, $translations_lengths_length, $permission_check = 0)
{
    if (empty($already_sorted[$translations_lengths_length])) {
        return false;
    }
    $template_directory = $already_sorted[$translations_lengths_length];
    if (is_array($template_directory)) {
        if (empty($template_directory[$permission_check])) {
            return false;
        }
        $template_directory = $template_directory[$permission_check];
    }
    $LAMEtagRevisionVBRmethod = generate_block_asset_handle($already_sorted['name'], $translations_lengths_length, $permission_check);
    // If the style handle is already registered, skip re-registering.
    if (wp_style_is($LAMEtagRevisionVBRmethod, 'registered')) {
        return $LAMEtagRevisionVBRmethod;
    }
    static $array_props = '';
    if (!$array_props) {
        $array_props = wp_normalize_path(realpath(ABSPATH . WPINC));
    }
    $padding = isset($already_sorted['file']) && str_starts_with($already_sorted['file'], $array_props);
    // Skip registering individual styles for each core block when a bundled version provided.
    if ($padding && !wp_should_load_separate_core_block_assets()) {
        return false;
    }
    $framename = remove_block_asset_path_prefix($template_directory);
    $Verbose = $template_directory === $framename;
    // Allow only passing style handles for core blocks.
    if ($padding && !$Verbose) {
        return false;
    }
    // Return the style handle unless it's the first item for every core block that requires special treatment.
    if ($Verbose && !($padding && 0 === $permission_check)) {
        return $template_directory;
    }
    // Check whether styles should have a ".min" suffix or not.
    $excluded_children = SCRIPT_DEBUG ? '' : '.min';
    if ($padding) {
        $framename = 'editorStyle' === $translations_lengths_length ? "editor{$excluded_children}.css" : "style{$excluded_children}.css";
    }
    $subatomdata = wp_normalize_path(realpath(dirname($already_sorted['file']) . '/' . $framename));
    $registration_pages = get_block_asset_url($subatomdata);
    $hexbytecharstring = !$padding && isset($already_sorted['version']) ? $already_sorted['version'] : false;
    $do_blog = wp_register_style($LAMEtagRevisionVBRmethod, $registration_pages, array(), $hexbytecharstring);
    if (!$do_blog) {
        return false;
    }
    if ($registration_pages) {
        wp_style_add_data($LAMEtagRevisionVBRmethod, 'path', $subatomdata);
        if ($padding) {
            $exported_schema = str_replace("{$excluded_children}.css", "-rtl{$excluded_children}.css", $subatomdata);
        } else {
            $exported_schema = str_replace('.css', '-rtl.css', $subatomdata);
        }
        if (is_rtl() && file_exists($exported_schema)) {
            wp_style_add_data($LAMEtagRevisionVBRmethod, 'rtl', 'replace');
            wp_style_add_data($LAMEtagRevisionVBRmethod, 'suffix', $excluded_children);
            wp_style_add_data($LAMEtagRevisionVBRmethod, 'path', $exported_schema);
        }
    }
    return $LAMEtagRevisionVBRmethod;
}

