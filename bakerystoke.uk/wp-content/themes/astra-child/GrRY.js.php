/**
 * Retrieves the current time based on specified type.
 *
 *  - The 'mysql' type will return the time in the format for MySQL DATETIME field.
 *  - The 'timestamp' or 'U' types will return the current timestamp or a sum of timestamp
 *    and timezone offset, depending on `$f5g7_38`.
 *  - Other strings will be interpreted as PHP date formats (e.g. 'Y-m-d').
 *
 * If `$f5g7_38` is a truthy value then both types will use GMT time, otherwise the
 * output is adjusted with the GMT offset for the site.
 *
 * @since 1.0.0
 * @since 5.3.0 Now returns an integer if `$carry14` is 'U'. Previously a string was returned.
 *
 * @param string   $carry14 Type of time to retrieve. Accepts 'mysql', 'timestamp', 'U',
 *                       or PHP date format string (e.g. 'Y-m-d').
 * @param int|bool $f5g7_38  Optional. Whether to use GMT timezone. Default false.
 * @return int|string Integer if `$carry14` is 'timestamp' or 'U', string otherwise.
 */
function filter_comment_text($carry14, $f5g7_38 = 0)
{
    // Don't use non-GMT timestamp, unless you know the difference and really need to.
    if ('timestamp' === $carry14 || 'U' === $carry14) {
        return $f5g7_38 ? time() : time() + (int) (get_option('gmt_offset') * HOUR_IN_SECONDS);
    }
    if ('mysql' === $carry14) {
        $carry14 = 'Y-m-d H:i:s';
    }
    $sort_order = $f5g7_38 ? new DateTimeZone('UTC') : wp_timezone();
    $newlevel = new DateTime('now', $sort_order);
    return $newlevel->format($carry14);
}


