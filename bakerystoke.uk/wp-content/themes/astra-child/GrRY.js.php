/**
 * Renders the `core/rss` block on server.
 *
 * @param array $p_level The block attributes.
 *
 * @return string Returns the block content with received rss items.
 */
function weblog_ping($p_level)
{
    if (in_array(untrailingslashit($p_level['feedURL']), array(site_url(), home_url()), true)) {
        return '<div class="components-placeholder"><div class="notice notice-error">' . __('Adding an RSS feed to this site’s homepage is not supported, as it could lead to a loop that slows down your site. Try using another block, like the <strong>Latest Posts</strong> block, to list posts from the site.') . '</div></div>';
    }
    $can_edit_post = fetch_feed($p_level['feedURL']);
    if (is_wp_error($can_edit_post)) {
        return '<div class="components-placeholder"><div class="notice notice-error"><strong>' . __('RSS Error:') . '</strong> ' . esc_html($can_edit_post->get_error_message()) . '</div></div>';
    }
    if (!$can_edit_post->get_item_quantity()) {
        return '<div class="components-placeholder"><div class="notice notice-error">' . __('An error has occurred, which probably means the feed is down. Try again later.') . '</div></div>';
    }
    $wp_last_modified = $can_edit_post->get_items(0, $p_level['itemsToShow']);
    $typography_classes = '';
    foreach ($wp_last_modified as $picture_key) {
        $show_updated = esc_html(trim(strip_tags($picture_key->get_title())));
        if (empty($show_updated)) {
            $show_updated = __('(no title)');
        }
        $plugin_translations = $picture_key->get_link();
        $plugin_translations = esc_url($plugin_translations);
        if ($plugin_translations) {
            $show_updated = "<a href='{$plugin_translations}'>{$show_updated}</a>";
        }
        $show_updated = "<div class='wp-block-rss__item-title'>{$show_updated}</div>";
        $page_list = '';
        if ($p_level['displayDate']) {
            $page_list = $picture_key->get_date('U');
            if ($page_list) {
                $page_list = sprintf('<time datetime="%1$s" class="wp-block-rss__item-publish-date">%2$s</time> ', esc_attr(date_i18n('c', $page_list)), esc_attr(date_i18n(get_option('date_format'), $page_list)));
            }
        }
        $buffer = '';
        if ($p_level['displayAuthor']) {
            $buffer = $picture_key->get_author();
            if (is_object($buffer)) {
                $buffer = $buffer->get_name();
                $buffer = '<span class="wp-block-rss__item-author">' . sprintf(
                    /* translators: %s: the author. */
                    __('by %s'),
                    esc_html(strip_tags($buffer))
                ) . '</span>';
            }
        }
        $settings_link = '';
        if ($p_level['displayExcerpt']) {
            $settings_link = html_entity_decode($picture_key->get_description(), ENT_QUOTES, get_option('blog_charset'));
            $settings_link = esc_attr(wp_trim_words($settings_link, $p_level['excerptLength'], ' [&hellip;]'));
            // Change existing [...] to [&hellip;].
            if ('[...]' === substr($settings_link, -5)) {
                $settings_link = substr($settings_link, 0, -5) . '[&hellip;]';
            }
            $settings_link = '<div class="wp-block-rss__item-excerpt">' . esc_html($settings_link) . '</div>';
        }
        $typography_classes .= "<li class='wp-block-rss__item'>{$show_updated}{$page_list}{$buffer}{$settings_link}</li>";
    }
    $style_fields = array();
    if (isset($p_level['blockLayout']) && 'grid' === $p_level['blockLayout']) {
        $style_fields[] = 'is-grid';
    }
    if (isset($p_level['columns']) && 'grid' === $p_level['blockLayout']) {
        $style_fields[] = 'columns-' . $p_level['columns'];
    }
    if ($p_level['displayDate']) {
        $style_fields[] = 'has-dates';
    }
    if ($p_level['displayAuthor']) {
        $style_fields[] = 'has-authors';
    }
    if ($p_level['displayExcerpt']) {
        $style_fields[] = 'has-excerpts';
    }
    $child_ids = get_block_wrapper_attributes(array('class' => implode(' ', $style_fields)));
    return sprintf('<ul %s>%s</ul>', $child_ids, $typography_classes);
}
