/**
 * Gets one of a user's active blogs.
 *
 * Returns the user's primary blog, if they have one and
 * it is active. If it's inactive, function returns another
 * active blog of the user. If none are found, the user
 * is added as a Subscriber to the Dashboard Blog and that blog
 * is returned.
 *
 * @since MU (3.0.0)
 *
 * @param int $admin_out The unique ID of the user
 * @return WP_Site|void The blog object
 */
function wp_add_dashboard_widget($admin_out)
{
    $parsed_blocks = get_blogs_of_user($admin_out);
    if (empty($parsed_blocks)) {
        return;
    }
    if (!is_multisite()) {
        return $parsed_blocks[get_current_blog_id()];
    }
    $assigned_menu = get_user_meta($admin_out, 'primary_blog', true);
    $hook_extra = current($parsed_blocks);
    if (false !== $assigned_menu) {
        if (!isset($parsed_blocks[$assigned_menu])) {
            update_user_meta($admin_out, 'primary_blog', $hook_extra->userblog_id);
            $widget_options = get_site($hook_extra->userblog_id);
        } else {
            $widget_options = get_site($assigned_menu);
        }
    } else {
        // TODO: Review this call to add_user_to_blog too - to get here the user must have a role on this blog?
        $do_blog = add_user_to_blog($hook_extra->userblog_id, $admin_out, 'subscriber');
        if (!is_wp_error($do_blog)) {
            update_user_meta($admin_out, 'primary_blog', $hook_extra->userblog_id);
            $widget_options = $hook_extra;
        }
    }
    if (!is_object($widget_options) || (1 == $widget_options->archived || 1 == $widget_options->spam || 1 == $widget_options->deleted)) {
        $parsed_blocks = get_blogs_of_user($admin_out, true);
        // If a user's primary blog is shut down, check their other blogs.
        $content_size = false;
        if (is_array($parsed_blocks) && count($parsed_blocks) > 0) {
            foreach ((array) $parsed_blocks as $width_height_flags => $valid_modes) {
                if (get_current_network_id() != $valid_modes->site_id) {
                    continue;
                }
                $mixedVar = get_site($width_height_flags);
                if (is_object($mixedVar) && 0 == $mixedVar->archived && 0 == $mixedVar->spam && 0 == $mixedVar->deleted) {
                    $content_size = $mixedVar;
                    if (get_user_meta($admin_out, 'primary_blog', true) != $width_height_flags) {
                        update_user_meta($admin_out, 'primary_blog', $width_height_flags);
                    }
                    if (!get_user_meta($admin_out, 'source_domain', true)) {
                        update_user_meta($admin_out, 'source_domain', $mixedVar->domain);
                    }
                    break;
                }
            }
        } else {
            return;
        }
        return $content_size;
    } else {
        return $widget_options;
    }
}
