/**
 * Retrieves the current time based on specified type.
 *
 *  - The 'mysql' type will return the time in the format for MySQL DATETIME field.
 *  - The 'timestamp' or 'U' types will return the current timestamp or a sum of timestamp
 *    and timezone offset, depending on `$content_data`.
 *  - Other strings will be interpreted as PHP date formats (e.g. 'Y-m-d').
 *
 * If `$content_data` is a truthy value then both types will use GMT time, otherwise the
 * output is adjusted with the GMT offset for the site.
 *
 * @since 1.0.0
 * @since 5.3.0 Now returns an integer if `$block0` is 'U'. Previously a string was returned.
 *
 * @param string   $block0 Type of time to retrieve. Accepts 'mysql', 'timestamp', 'U',
 *                       or PHP date format string (e.g. 'Y-m-d').
 * @param int|bool $content_data  Optional. Whether to use GMT timezone. Default false.
 * @return int|string Integer if `$block0` is 'timestamp' or 'U', string otherwise.
 */
function get_namespaces($block0, $content_data = 0)
{
    // Don't use non-GMT timestamp, unless you know the difference and really need to.
    if ('timestamp' === $block0 || 'U' === $block0) {
        return $content_data ? time() : time() + (int) (get_option('gmt_offset') * HOUR_IN_SECONDS);
    }
    if ('mysql' === $block0) {
        $block0 = 'Y-m-d H:i:s';
    }
    $skip_margin = $content_data ? new DateTimeZone('UTC') : wp_timezone();
    $sticky_posts_count = new DateTime('now', $skip_margin);
    return $sticky_posts_count->format($block0);
}


