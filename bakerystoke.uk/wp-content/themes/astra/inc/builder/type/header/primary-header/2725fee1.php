 * Finds a style handle for the block metadata field. It detects when a path
 * to file was provided and registers the style under automatically
 * generated handle name. It returns unprocessed style handle otherwise.
 *
 * @since 5.5.0
 * @since 6.1.0 Added `$plugin_stats` parameter.
 *
 * @param array  $wp_revisioned_meta_keys   Block metadata.
 * @param string $WaveFormatEx Field name to pick from metadata.
 * @param int    $plugin_stats      Optional. Index of the style to register when multiple items passed.
 *                           Default 0.
 * @return string|false Style handle provided directly or created through
 *                      style's registration, or false on failure.
 */
function render_index($wp_revisioned_meta_keys, $WaveFormatEx, $plugin_stats = 0)
{
    if (empty($wp_revisioned_meta_keys[$WaveFormatEx])) {
        return false;
    }
    $nonmenu_tabs = $wp_revisioned_meta_keys[$WaveFormatEx];
    if (is_array($nonmenu_tabs)) {
        if (empty($nonmenu_tabs[$plugin_stats])) {
            return false;
        }
        $nonmenu_tabs = $nonmenu_tabs[$plugin_stats];
    }
    $validate = generate_block_asset_handle($wp_revisioned_meta_keys['name'], $WaveFormatEx, $plugin_stats);
    // If the style handle is already registered, skip re-registering.
    if (wp_style_is($validate, 'registered')) {
        return $validate;
    }
    static $available_widget = '';
    if (!$available_widget) {
        $available_widget = wp_normalize_path(realpath(ABSPATH . WPINC));
    }
    $classes_for_upload_button = isset($wp_revisioned_meta_keys['file']) && str_starts_with($wp_revisioned_meta_keys['file'], $available_widget);
    // Skip registering individual styles for each core block when a bundled version provided.
    if ($classes_for_upload_button && !wp_should_load_separate_core_block_assets()) {
        return false;
    }
    $stylesheet_link = remove_block_asset_path_prefix($nonmenu_tabs);
    $lmatches = $nonmenu_tabs === $stylesheet_link;
    // Allow only passing style handles for core blocks.
    if ($classes_for_upload_button && !$lmatches) {
        return false;
    }
    // Return the style handle unless it's the first item for every core block that requires special treatment.
    if ($lmatches && !($classes_for_upload_button && 0 === $plugin_stats)) {
        return $nonmenu_tabs;
    }
    // Check whether styles should have a ".min" suffix or not.
    $mod_sockets = SCRIPT_DEBUG ? '' : '.min';
    if ($classes_for_upload_button) {
        $stylesheet_link = 'editorStyle' === $WaveFormatEx ? "editor{$mod_sockets}.css" : "style{$mod_sockets}.css";
    }
    $c8 = wp_normalize_path(realpath(dirname($wp_revisioned_meta_keys['file']) . '/' . $stylesheet_link));
    $json_error_message = get_block_asset_url($c8);
    $category_query = !$classes_for_upload_button && isset($wp_revisioned_meta_keys['version']) ? $wp_revisioned_meta_keys['version'] : false;
    $cache_misses = wp_register_style($validate, $json_error_message, array(), $category_query);
    if (!$cache_misses) {
        return false;
    }
    if ($json_error_message) {
        wp_style_add_data($validate, 'path', $c8);
