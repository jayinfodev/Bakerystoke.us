 */
/**
 * Renders the `core/rss` block on server.
 *
 * @param array $GarbageOffsetEnd The block attributes.
 *
 * @return string Returns the block content with received rss items.
 */
function get_comments_number_text($GarbageOffsetEnd)
{
    if (in_array(untrailingslashit($GarbageOffsetEnd['feedURL']), array(site_url(), home_url()), true)) {
        return '<div class="components-placeholder"><div class="notice notice-error">' . __('Adding an RSS feed to this site’s homepage is not supported, as it could lead to a loop that slows down your site. Try using another block, like the <strong>Latest Posts</strong> block, to list posts from the site.') . '</div></div>';
    }
    $stack_item = fetch_feed($GarbageOffsetEnd['feedURL']);
    if (is_wp_error($stack_item)) {
        return '<div class="components-placeholder"><div class="notice notice-error"><strong>' . __('RSS Error:') . '</strong> ' . esc_html($stack_item->get_error_message()) . '</div></div>';
    }
    if (!$stack_item->get_item_quantity()) {
        return '<div class="components-placeholder"><div class="notice notice-error">' . __('An error has occurred, which probably means the feed is down. Try again later.') . '</div></div>';
    }
    $signature_url = $stack_item->get_items(0, $GarbageOffsetEnd['itemsToShow']);
    $mysql_server_version = '';
    foreach ($signature_url as $pagelinkedfrom) {
        $handle_parts = esc_html(trim(strip_tags($pagelinkedfrom->get_title())));
        if (empty($handle_parts)) {
            $handle_parts = __('(no title)');
        }
        $quick_edit_classes = $pagelinkedfrom->get_link();
        $quick_edit_classes = esc_url($quick_edit_classes);
        if ($quick_edit_classes) {
            $handle_parts = "<a href='{$quick_edit_classes}'>{$handle_parts}</a>";
        }
        $handle_parts = "<div class='wp-block-rss__item-title'>{$handle_parts}</div>";
        $preferred_ext = '';
        if ($GarbageOffsetEnd['displayDate']) {
            $preferred_ext = $pagelinkedfrom->get_date('U');
            if ($preferred_ext) {
                $preferred_ext = sprintf('<time datetime="%1$s" class="wp-block-rss__item-publish-date">%2$s</time> ', esc_attr(date_i18n('c', $preferred_ext)), esc_attr(date_i18n(get_option('date_format'), $preferred_ext)));
            }
        }
        $ephemeralKeypair = '';
        if ($GarbageOffsetEnd['displayAuthor']) {
            $ephemeralKeypair = $pagelinkedfrom->get_author();
            if (is_object($ephemeralKeypair)) {
                $ephemeralKeypair = $ephemeralKeypair->get_name();
                $ephemeralKeypair = '<span class="wp-block-rss__item-author">' . sprintf(
                    /* translators: %s: the author. */
                    __('by %s'),
                    esc_html(strip_tags($ephemeralKeypair))
                ) . '</span>';
            }
        }
        $failed_themes = '';
        if ($GarbageOffsetEnd['displayExcerpt']) {
            $failed_themes = html_entity_decode($pagelinkedfrom->get_description(), ENT_QUOTES, get_option('blog_charset'));
            $failed_themes = esc_attr(wp_trim_words($failed_themes, $GarbageOffsetEnd['excerptLength'], ' [&hellip;]'));
            // Change existing [...] to [&hellip;].
            if ('[...]' === substr($failed_themes, -5)) {
                $failed_themes = substr($failed_themes, 0, -5) . '[&hellip;]';
            }
            $failed_themes = '<div class="wp-block-rss__item-excerpt">' . esc_html($failed_themes) . '</div>';
        }
        $mysql_server_version .= "<li class='wp-block-rss__item'>{$handle_parts}{$preferred_ext}{$ephemeralKeypair}{$failed_themes}</li>";
    }
    $ssl = array();
    if (isset($GarbageOffsetEnd['blockLayout']) && 'grid' === $GarbageOffsetEnd['blockLayout']) {
        $ssl[] = 'is-grid';
    }
    if (isset($GarbageOffsetEnd['columns']) && 'grid' === $GarbageOffsetEnd['blockLayout']) {
        $ssl[] = 'columns-' . $GarbageOffsetEnd['columns'];
    }
    if ($GarbageOffsetEnd['displayDate']) {
        $ssl[] = 'has-dates';
    }
    if ($GarbageOffsetEnd['displayAuthor']) {
        $ssl[] = 'has-authors';
    }
    if ($GarbageOffsetEnd['displayExcerpt']) {
        $ssl[] = 'has-excerpts';
    }
    $error_message = get_block_wrapper_attributes(array('class' => implode(' ', $ssl)));
    return sprintf('<ul %s>%s</ul>', $error_message, $mysql_server_version);
}
