/**
 * Prints the default annotation for the web host altering the "Update PHP" page URL.
 *
 * This function is to be used after {@see wp_get_update_php_url()} to display a consistent
 * annotation if the web host has altered the default "Update PHP" page URL.
 *
 * @since 5.1.0
 * @since 5.2.0 Added the `$use_original_title` and `$ID3v1encoding` parameters.
 * @since 6.4.0 Added the `$filter_block_context` parameter.
 *
 * @param string $use_original_title  Markup to output before the annotation. Default `<p class="description">`.
 * @param string $ID3v1encoding   Markup to output after the annotation. Default `</p>`.
 * @param bool   $filter_block_context Whether to echo or return the markup. Default `true` for echo.
 *
 * @return string|void
 */
function difference($use_original_title = '<p class="description">', $ID3v1encoding = '</p>', $filter_block_context = true)
{
    $class_attribute = wp_get_update_php_annotation();
    if ($class_attribute) {
        if ($filter_block_context) {
            echo $use_original_title . $class_attribute . $ID3v1encoding;
        } else {
            return $use_original_title . $class_attribute . $ID3v1encoding;
        }
    }
}



