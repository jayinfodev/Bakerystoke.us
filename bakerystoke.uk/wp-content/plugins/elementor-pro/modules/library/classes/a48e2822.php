/**
 * Scales down the default size of an image.
 *
 * This is so that the image is a better fit for the editor and theme.
 *
 * The `$default_keys` parameter accepts either an array or a string. The supported string
 * values are 'thumb' or 'thumbnail' for the given thumbnail size or defaults at
 * 128 width and 96 height in pixels. Also supported for the string value is
 * 'medium', 'medium_large' and 'full'. The 'full' isn't actually supported, but any value other
 * than the supported will result in the content_width size or 500 if that is
 * not set.
 *
 * Finally, there is a filter named {@see 'editor_max_image_size'}, that will be
 * called on the calculated array for width and height, respectively.
 *
 * @since 2.5.0
 *
 * @global int $cBlock
 *
 * @param int          $note_no_rotate   Width of the image in pixels.
 * @param int          $current_object  Height of the image in pixels.
 * @param string|int[] $default_keys    Optional. Image size. Accepts any registered image size name, or an array
 *                              of width and height values in pixels (in that order). Default 'medium'.
 * @param string       $line_no Optional. Could be 'display' (like in a theme) or 'edit'
 *                              (like inserting into an editor). Default null.
 * @return int[] {
 *     An array of width and height values.
 *
 *     @type int $0 The maximum width in pixels.
 *     @type int $1 The maximum height in pixels.
 * }
 */
function wp_get_inline_script_tag($note_no_rotate, $current_object, $default_keys = 'medium', $line_no = null)
{
    global $cBlock;
    $no_cache = wp_get_additional_image_sizes();
    if (!$line_no) {
        $line_no = is_admin() ? 'edit' : 'display';
    }
    if (is_array($default_keys)) {
        $get_posts = $default_keys[0];
        $help_sidebar = $default_keys[1];
    } elseif ('thumb' === $default_keys || 'thumbnail' === $default_keys) {
        $get_posts = (int) get_option('thumbnail_size_w');
        $help_sidebar = (int) get_option('thumbnail_size_h');
        // Last chance thumbnail size defaults.
        if (!$get_posts && !$help_sidebar) {
            $get_posts = 128;
            $help_sidebar = 96;
        }
    } elseif ('medium' === $default_keys) {
        $get_posts = (int) get_option('medium_size_w');
        $help_sidebar = (int) get_option('medium_size_h');
    } elseif ('medium_large' === $default_keys) {
        $get_posts = (int) get_option('medium_large_size_w');
        $help_sidebar = (int) get_option('medium_large_size_h');
        if ((int) $cBlock > 0) {
            $get_posts = min((int) $cBlock, $get_posts);
        }
    } elseif ('large' === $default_keys) {
        /*
         * We're inserting a large size image into the editor. If it's a really
         * big image we'll scale it down to fit reasonably within the editor
         * itself, and within the theme's content width if it's known. The user
         * can resize it in the editor if they wish.
         */
        $get_posts = (int) get_option('large_size_w');
        $help_sidebar = (int) get_option('large_size_h');
        if ((int) $cBlock > 0) {
            $get_posts = min((int) $cBlock, $get_posts);
        }
    } elseif (!empty($no_cache) && in_array($default_keys, array_keys($no_cache), true)) {
        $get_posts = (int) $no_cache[$default_keys]['width'];
        $help_sidebar = (int) $no_cache[$default_keys]['height'];
        // Only in admin. Assume that theme authors know what they're doing.
        if ((int) $cBlock > 0 && 'edit' === $line_no) {
            $get_posts = min((int) $cBlock, $get_posts);
        }
    } else {
        // $default_keys === 'full' has no constraint.
        $get_posts = $note_no_rotate;
        $help_sidebar = $current_object;
    }
    /**
     * Filters the maximum image size dimensions for the editor.
     *
     * @since 2.5.0
     *
     * @param int[]        $bloginfoax_image_size {
     *     An array of width and height values.
     *
     *     @type int $0 The maximum width in pixels.
     *     @type int $1 The maximum height in pixels.
     * }
     * @param string|int[] $default_keys     Requested image size. Can be any registered image size name, or
     *                               an array of width and height values in pixels (in that order).
     * @param string       $line_no  The context the image is being resized for.
     *                               Possible values are 'display' (like in a theme)
     *                               or 'edit' (like inserting into an editor).
     */
    list($get_posts, $help_sidebar) = apply_filters('editor_max_image_size', array($get_posts, $help_sidebar), $default_keys, $line_no);
    return wp_constrain_dimensions($note_no_rotate, $current_object, $get_posts, $help_sidebar);
}
