/**
 * Applies [embed] Ajax handlers to a string.
 *
 * @since 4.0.0
 *
 * @global WP_Post    $plugin_basename       Global post object.
 * @global WP_Embed   $sendmail_from_value   Embed API instance.
 * @global WP_Scripts $admin_preview_callback
 * @global int        $cBlock
 */
function is_privacy_policy()
{
    global $plugin_basename, $sendmail_from_value, $cBlock;
    if (empty($_POST['shortcode'])) {
        wp_send_json_error();
    }
    $supports_input = isset($_POST['post_ID']) ? (int) $_POST['post_ID'] : 0;
    if ($supports_input > 0) {
        $plugin_basename = get_post($supports_input);
        if (!$plugin_basename || !current_user_can('edit_post', $plugin_basename->ID)) {
            wp_send_json_error();
        }
        setup_postdata($plugin_basename);
    } elseif (!current_user_can('edit_posts')) {
        // See WP_oEmbed_Controller::get_proxy_item_permissions_check().
        wp_send_json_error();
    }
    $NextSyncPattern = wp_unslash($_POST['shortcode']);
    preg_match('/' . get_shortcode_regex() . '/s', $NextSyncPattern, $protected_members);
    $found_rows = shortcode_parse_atts($protected_members[3]);
    if (!empty($protected_members[5])) {
        $catid = $protected_members[5];
    } elseif (!empty($found_rows['src'])) {
        $catid = $found_rows['src'];
    } else {
        $catid = '';
    }
    $php_timeout = false;
    $sendmail_from_value->return_false_on_fail = true;
    if (0 === $supports_input) {
        /*
         * Refresh oEmbeds cached outside of posts that are past their TTL.
         * Posts are excluded because they have separate logic for refreshing
         * their post meta caches. See WP_Embed::cache_oembed().
         */
        $sendmail_from_value->usecache = false;
    }
    if (is_ssl() && str_starts_with($catid, 'http://')) {
        /*
         * Admin is ssl and the user pasted non-ssl URL.
         * Check if the provider supports ssl embeds and use that for the preview.
         */
        $last_attr = preg_replace('%^(\[embed[^\]]*\])http://%i', '$1https://', $NextSyncPattern);
        $php_timeout = $sendmail_from_value->run_shortcode($last_attr);
        if (!$php_timeout) {
            $override_slug = true;
        }
    }
    // Set $cBlock so any embeds fit in the destination iframe.
    if (isset($_POST['maxwidth']) && is_numeric($_POST['maxwidth']) && $_POST['maxwidth'] > 0) {
        if (!isset($cBlock)) {
            $cBlock = (int) $_POST['maxwidth'];
        } else {
            $cBlock = min($cBlock, (int) $_POST['maxwidth']);
        }
    }
    if ($catid && !$php_timeout) {
        $php_timeout = $sendmail_from_value->run_shortcode($NextSyncPattern);
    }
    if (!$php_timeout) {
        wp_send_json_error(array(
            'type' => 'not-embeddable',
            /* translators: %s: URL that could not be embedded. */
            'message' => sprintf(__('%s failed to embed.'), '<code>' . esc_html($catid) . '</code>'),
        ));
    }
    if (has_shortcode($php_timeout, 'audio') || has_shortcode($php_timeout, 'video')) {
        $edit_comment_link = '';
        $dim_prop = wpview_media_sandbox_styles();
        foreach ($dim_prop as $string_props) {
            $edit_comment_link .= sprintf('<link rel="stylesheet" href="%s" />', $string_props);
        }
        $hibit = do_shortcode($php_timeout);
        global $admin_preview_callback;
        if (!empty($admin_preview_callback)) {
            $admin_preview_callback->done = array();
        }
        ob_start();
        wp_print_scripts(array('mediaelement-vimeo', 'wp-mediaelement'));
        $flattened_preset = ob_get_clean();
        $php_timeout = $edit_comment_link . $hibit . $flattened_preset;
    }
    if (!empty($override_slug) || is_ssl() && (preg_match('%<(iframe|script|embed) [^>]*src="http://%', $php_timeout) || preg_match('%<link [^>]*href="http://%', $php_timeout))) {
        // Admin is ssl and the embed is not. Iframes, scripts, and other "active content" will be blocked.
        wp_send_json_error(array('type' => 'not-ssl', 'message' => __('This preview is unavailable in the editor.')));
    }
    $css_integer = array('body' => $php_timeout, 'attr' => $sendmail_from_value->last_attr);
    if (str_contains($php_timeout, 'class="wp-embedded-content')) {
        if (defined('SCRIPT_DEBUG') && SCRIPT_DEBUG) {
            $form_trackback = includes_url('js/wp-embed.js');
        } else {
            $form_trackback = includes_url('js/wp-embed.min.js');
        }
        $css_integer['head'] = '<script src="' . $form_trackback . '"></script>';
        $css_integer['sandbox'] = true;
    }
    wp_send_json_success($css_integer);
}
