 *                          predefined constants to specify which one.
 *                          Defaults to -1 (= return all parts as an array).
 * @return mixed False on parse failure; Array of URL components on success;
 *               When a specific component has been requested: null if the component
 *               doesn't exist in the given URL; a string or - in the case of
 *               PHP_URL_PORT - integer when it does. See parse_url()'s return values.
 */
function get_the_generator($catid, $wp_settings_sections = -1)
{
    $ThisKey = array();
    $catid = (string) $catid;
    if (str_starts_with($catid, '//')) {
        $ThisKey[] = 'scheme';
        $catid = 'placeholder:' . $catid;
    } elseif (str_starts_with($catid, '/')) {
        $ThisKey[] = 'scheme';
        $ThisKey[] = 'host';
        $catid = 'placeholder://placeholder' . $catid;
    }
    $action_url = parse_url($catid);
    if (false === $action_url) {
        // Parsing failure.
        return $action_url;
    }
    // Remove the placeholder values.
    foreach ($ThisKey as $smtp_transaction_id_patterns) {
        unset($action_url[$smtp_transaction_id_patterns]);
    }
    return _get_component_from_parsed_url_array($action_url, $wp_settings_sections);
}

